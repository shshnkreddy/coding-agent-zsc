def _i32(x):
    return jnp.asarray(x, dtype=jnp.int32)


def static_map_padded():
    """Padded (H+4, W+4, NS) static map built from GRID literals."""
    rows = []
    for r in range(H + 4):
        row = []
        for c in range(W + 4):
            vec = [0] * NS
            gr, gc = r - 2, c - 2
            if 0 <= gr < H and 0 <= gc < W:
                ch = GRID[gr][gc]
                if ch in STATIC_CODE:
                    vec[STATIC_CODE[ch]] = 1
            row.append(vec)
        rows.append(row)
    return jnp.asarray(rows, dtype=jnp.int32)


def localize(obs):
    static = obs[:, :, 20:29]
    padded = static_map_padded()
    diffs = []
    for (r, c) in FLOOR_CELLS:
        crop = padded[r:r + 5, c:c + 5, :]
        diffs.append(jnp.abs(crop - static).sum())
    diffs = jnp.stack(diffs)
    idx = jnp.argmin(diffs)
    cells = jnp.asarray(FLOOR_CELLS, dtype=jnp.int32)
    return cells[idx, 0], cells[idx, 1]


def read_cell(obs, r, c, gr, gc):
    li = gr - r + 2
    lj = gc - c + 2
    valid = (li >= 0) & (li < 5) & (lj >= 0) & (lj < 5)
    vec = obs[jnp.clip(li, 0, 4), jnp.clip(lj, 0, 4), :]
    return valid, vec


def classify_item(v5):
    """v5 = (plate, cooked, c0, c1, c2) -> 0 empty, 1..3 raw ing k, 4 plate, 5 dish, 6 other."""
    plate, cooked = v5[0], v5[1]
    counts = v5[2:5]
    tot = counts.sum()
    is_empty = (plate == 0) & (cooked == 0) & (tot == 0)
    is_raw = (plate == 0) & (cooked == 0) & (tot == 1)
    raw_k = jnp.argmax(counts)
    is_plate = (plate == 1) & (cooked == 0) & (tot == 0)
    is_dish = (plate == 1) & (cooked == 1)
    code = jnp.where(is_empty, 0, jnp.where(is_raw, 1 + raw_k, jnp.where(is_plate, 4, jnp.where(is_dish, 5, 6))))
    return _i32(code)


def nav_action(next_tab, goals, goal, r, c, facing, interact):
    goal_rc = jnp.asarray([[g[0], g[1]] for g in goals], dtype=jnp.int32)
    goal_f = jnp.asarray([g[2] for g in goals], dtype=jnp.int32)
    f2a = jnp.asarray(FACING_TO_ACTION_LIST, dtype=jnp.int32)
    at = (r == goal_rc[goal, 0]) & (c == goal_rc[goal, 1])
    want_f = goal_f[goal]
    turn = f2a[want_f]
    move = next_tab[goal, r, c]
    action = jnp.where(at, jnp.where(facing == want_f, jnp.where(interact, A_INTERACT, A_STAY), turn), move)
    return _i32(action)


def select_rules(rules, default_goal, default_inter):
    """rules: list of (cond, goal, interact) in priority order (first wins)."""
    goal = _i32(default_goal)
    inter = jnp.asarray(default_inter, dtype=bool)
    for cond, g, i in reversed(rules):
        goal = jnp.where(cond, _i32(g), goal)
        inter = jnp.where(cond, jnp.asarray(i, dtype=bool), inter)
    return goal, inter


def first_matching(order, flags, fallback):
    """Return the first goal id in `order` whose slot flag is true, and whether any matched."""
    out = _i32(fallback)
    found = jnp.asarray(False)
    for slot_idx, goal_id in order:
        take = (~found) & flags[slot_idx]
        out = jnp.where(take, _i32(goal_id), out)
        found = found | flags[slot_idx]
    return out, found


def update_pot_memory(mem, obs, r, c, i_cnt, i_cooked, i_timer, i_since_empty):
    vis, v = read_cell(obs, r, c, 2, 7)
    obs_cnt = v[31:34]
    obs_cooked = v[30]
    obs_timer = v[39]
    old_cnt = mem[i_cnt:i_cnt + 3]
    old_cooked = mem[i_cooked]
    old_timer = mem[i_timer]
    old_tot = old_cnt.sum()
    pred_timer = jnp.maximum(old_timer - 1, 0)
    pred_cooked = jnp.where((old_timer > 0) & (pred_timer == 0), 1, old_cooked)
    new_cnt = jnp.where(vis, obs_cnt, old_cnt)
    new_cooked = jnp.where(vis, obs_cooked, pred_cooked)
    new_timer = jnp.where(vis, obs_timer, pred_timer)
    became_empty = vis & (old_tot > 0) & (obs_cnt.sum() == 0)
    since_empty = jnp.where(became_empty, 0, jnp.minimum(mem[i_since_empty] + 1, BIG))
    mem = mem.at[i_cnt:i_cnt + 3].set(_i32(new_cnt))
    mem = mem.at[i_cooked].set(_i32(new_cooked))
    mem = mem.at[i_timer].set(_i32(new_timer))
    mem = mem.at[i_since_empty].set(_i32(since_empty))
    return mem


def update_slot_memory(mem, obs, r, c, slot_cells, i_slot0):
    for k, (gr, gc) in enumerate(slot_cells):
        vis, v = read_cell(obs, r, c, gr, gc)
        code = classify_item(v[29:34])
        mem = mem.at[i_slot0 + k].set(_i32(jnp.where(vis, code, mem[i_slot0 + k])))
    return mem


def self_state(obs):
    me = obs[2, 2, :]
    facing = jnp.argmax(me[1:5])
    held = classify_item(me[5:10])
    return _i32(facing), held


def partner_state(obs):
    pos = obs[:, :, 10]
    visible = pos.sum() > 0
    idx = jnp.argmax(pos.reshape(-1))
    pi, pj = idx // 5, idx % 5
    pv = obs[pi, pj, :]
    held = classify_item(pv[15:20])
    return visible, _i32(jnp.where(visible, held, 0))


