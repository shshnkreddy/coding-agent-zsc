# Agent 0: recipe reader and pot filler (left room)
# --------------------------------------------------------------------------
M0_RECIPE = 0        # -1 unknown else 0/1/2
M0_CNT = 1           # 1..3
M0_COOKED = 4
M0_TIMER = 5
M0_SINCE_EMPTY = 6
M0_SLOT = 7          # 7..14 (8 slots)
M0_PDISH = 15        # steps since partner seen holding a dish
M0_STEP = 16
M0_STALL = 17
M0_POTSIG = 18
M0_BAN = 19          # 1 once a partner has removed a staged item from (1,7)/(3,7) unhelpfully
M0_LAST_PICK = 20    # 1 if my previous action was a pickup from (1,7)/(3,7)
STAGE_MIN_TIMER = 10


def init_agent_0():
    m = [0] * MEM_SIZE
    m[M0_RECIPE] = -1
    m[M0_SINCE_EMPTY] = BIG
    m[M0_PDISH] = BIG
    return jnp.asarray(m, dtype=jnp.int32)


def agent_0_act(obs, reset, memory, rng):
    mem = jnp.where(reset, init_agent_0(), memory)
    obs = jnp.asarray(obs, dtype=jnp.int32)
    r, c = localize(obs)
    facing, held = self_state(obs)

    # --- recipe ---
    rec = mem[M0_RECIPE]
    for (gr, gc) in ((0, 5), (4, 5)):
        vis, v = read_cell(obs, r, c, gr, gc)
        rv = v[36:39]
        shown = vis & (rv.sum() > 0)
        rec = jnp.where(shown, jnp.argmax(rv), rec)
    rec = _i32(rec)
    mem = mem.at[M0_RECIPE].set(rec)
    rk = rec >= 0
    R = jnp.clip(rec, 0, 2)

    # --- pot / slots / partner ---
    mem = update_pot_memory(mem, obs, r, c, M0_CNT, M0_COOKED, M0_TIMER, M0_SINCE_EMPTY)
    old_slots = mem[M0_SLOT:M0_SLOT + 8]
    mem = update_slot_memory(mem, obs, r, c, SLOT_CELLS_0, M0_SLOT)
    pvis, pheld = partner_state(obs)
    pdish_now = pvis & (pheld == 5)
    pdish = _i32(jnp.where(pdish_now, 0, jnp.minimum(mem[M0_PDISH] + 1, BIG)))
    mem = mem.at[M0_PDISH].set(pdish)
    mem = mem.at[M0_STEP].set(mem[M0_STEP] + 1)

    cnt = mem[M0_CNT:M0_CNT + 3]
    cooked = mem[M0_COOKED]
    timer = mem[M0_TIMER]
    tot = cnt.sum()
    pot_idle = (timer == 0) & (cooked == 0)
    cntR = cnt[R]
    nonR = tot - cntR
    # stall-breaker: pot idle with non-recipe contents and unchanged for a long time -> complete it
    sig = cnt[0] + 4 * cnt[1] + 16 * cnt[2] + 64 * cooked + 128 * (timer > 0)
    wrong_idle = rk & pot_idle & (tot > 0) & (tot < 3) & (nonR > 0)
    stall = _i32(jnp.where(wrong_idle & (sig == mem[M0_POTSIG]), jnp.minimum(mem[M0_STALL] + 1, BIG), 0))
    mem = mem.at[M0_STALL].set(stall)
    mem = mem.at[M0_POTSIG].set(_i32(sig))
    maj = _i32(jnp.where(cnt[1] > cnt[0], 1, 0))
    use_break = wrong_idle & (stall >= 30) & (cnt[2] == 0) & (mem[M0_STEP] < 330)
    R = _i32(jnp.where(use_break, maj, R))
    cntR = cnt[R]
    nonR = tot - cntR
    fillable = rk & pot_idle & (tot < 3) & (nonR == 0)
    safe = (mem[M0_SINCE_EMPTY] >= 3) & (pdish >= 2)
    slots = mem[M0_SLOT:M0_SLOT + 8]
    slot_empty = slots == 0

    held_raw = (held >= 1) & (held <= 3)
    hk = jnp.clip(held - 1, 0, 2)
    held_none = held == 0
    held_other = held >= 4

    # theft detection on the pass-through counters (1,7)/(3,7): an item I staged vanished without me
    # picking it up while the pot could not use it -> partner interferes -> stop staging there
    my_pick = mem[M0_LAST_PICK] == 1
    ban = mem[M0_BAN] == 1
    for k in (6, 7):
        was_raw = (old_slots[k] >= 1) & (old_slots[k] <= 3)
        gone = was_raw & (slots[k] == 0)
        helpful = (tot > 0) & (cnt[jnp.clip(old_slots[k] - 1, 0, 2)] == tot)
        ban = ban | (gone & ~my_pick & ~helpful)
    mem = mem.at[M0_BAN].set(_i32(ban))
    pass_ok = ~ban
    # a slot is usable for staging if empty and (not a pass-through slot or pass-through allowed)
    stage_empty = jnp.concatenate([slot_empty[:6], slot_empty[6:] & pass_ok])

    # slot preference orders (slot index, goal id); slots: 0=(0,4) g3, 1=(0,3) g4, 2=(4,4) g5, 3=(4,3) g6,
    # 4=(0,2) g7, 5=(4,2) g8, 6=(1,7) g9, 7=(3,7) g10
    order0 = [(6, 9), (0, 3), (1, 4), (4, 7), (5, 8), (7, 10), (2, 5), (3, 6)]
    order1 = [(7, 10), (2, 5), (3, 6), (5, 8), (4, 7), (6, 9), (0, 3), (1, 4)]
    order2 = [(4, 7), (5, 8), (0, 3), (1, 4), (2, 5), (3, 6), (6, 9), (7, 10)]

    def pick_order(k, flags):
        g0, f0 = first_matching(order0, flags, 2)
        g1, f1 = first_matching(order1, flags, 2)
        g2, f2 = first_matching(order2, flags, 2)
        g = jnp.where(k == 0, g0, jnp.where(k == 1, g1, g2))
        f = jnp.where(k == 0, f0, jnp.where(k == 1, f1, f2))
        return g, f

    stage_goal, stage_found = pick_order(hk, stage_empty)
    garb_goal, garb_found = first_matching(order2, stage_empty, 2)
    has_R = slots == (1 + R)
    src_goal, src_found = pick_order(R, has_R)
    supply_goal = jnp.where(R == 1, 1, 0)
    fetch_goal = jnp.where(src_found, src_goal, supply_goal)

    # staging plan when hands are empty and the pot cannot be loaded:
    # tier 1 = nearest slot per type ((1,7)/(3,7) if allowed, else (0,4)/(4,4)), tier 2 = next slot
    t1 = jnp.stack([jnp.where(pass_ok, stage_empty[6], stage_empty[0]),
                    jnp.where(pass_ok, stage_empty[7], stage_empty[2])])
    t2 = jnp.stack([jnp.where(pass_ok, stage_empty[0], stage_empty[1]),
                    jnp.where(pass_ok, stage_empty[2], stage_empty[3])])
    R01 = jnp.clip(R, 0, 1)
    other = 1 - R01
    want_t = jnp.where(t1[R01], R01,
             jnp.where(t1[other], other,
             jnp.where(t2[R01], R01,
             jnp.where(t2[other], other, -1))))
    stage_fetch_needed = want_t >= 0
    stage_fetch_goal = jnp.where(want_t == 1, 1, 0)
    # only start a staging trip when the pot will stay busy long enough for the round trip;
    # otherwise return to the pot so the emptying is observed promptly
    stage_ok = (timer >= STAGE_MIN_TIMER) | (wrong_idle & ~use_break)

    rules = [
        (held_raw & (hk == R) & fillable & safe, 2, True),
        (held_raw & (hk == R) & fillable & ~safe, 2, False),
        (held_raw & stage_found, stage_goal, True),
        (held_raw, 2, False),
        (held_other & garb_found, garb_goal, True),
        (held_other, 2, False),
        (held_none & ~rk, 2, False),
        (held_none & fillable, fetch_goal, True),
        (held_none & stage_fetch_needed & stage_ok, stage_fetch_goal, True),
    ]
    goal, inter = select_rules(rules, 2, False)
    next_tab = jnp.asarray(NEXT_0_TAB, dtype=jnp.int32)
    action = nav_action(next_tab, GOALS_0, goal, r, c, facing, inter)
    my_pick_now = (action == A_INTERACT) & held_none & ((goal == 9) | (goal == 10))
    mem = mem.at[M0_LAST_PICK].set(_i32(my_pick_now))

    trace = {
        'r': r, 'c': c, 'held': held, 'goal': goal, 'inter': inter.astype(jnp.int32),
        'recipe': rec, 'pot_tot': tot, 'timer': timer, 'cooked': cooked,
        'safe': safe.astype(jnp.int32), 'fillable': fillable.astype(jnp.int32),
        'ban': ban.astype(jnp.int32),
    }
    return action, mem, trace


# --------------------------------------------------------------------------
# Agent 1: pot completer, plater, deliverer (right room)
# --------------------------------------------------------------------------
M1_CNT = 0
M1_COOKED = 3
M1_TIMER = 4
M1_SINCE_EMPTY = 5
M1_SLOT = 6          # 6..9
M1_STEP = 10
M1_SINCE_DELIVER = 11   # steps since my last delivery (0 = the observation right after it)
M1_LAST_DELIVER = 12    # 1 if my previous action was a delivery interact
M1_SUSPECT = 13         # pot contents appeared before my delivery completed (recipe may have changed)
M1_EVWRONG = 14         # partner seen waiting at the pot holding a different ingredient than the pot
M1_MYUNITS = 15         # units I inserted into the current pot
M1_LAST_INSERT = 16     # 1 if my previous action was a pot insert interact
M1_DISH_BAD = 17        # the dish I am holding is judged stale -> park instead of deliver
M1_EMPTY_STEPS = 18     # consecutive steps the pot has been empty and idle
M1_HINT = 19            # holding an ingredient taken from a pass-through counter as a recipe hint
M1_FRESH = 20           # 20,21: counter (1,7)/(3,7) item appeared after my last delivery
M1_GARB = 22            # holding a stale counter item to relocate onto a spare counter
HINT_STALL = 40


def init_agent_1():
    m = [0] * MEM_SIZE
    m[M1_SINCE_EMPTY] = BIG
    m[M1_SINCE_DELIVER] = BIG
    return jnp.asarray(m, dtype=jnp.int32)


def agent_1_act(obs, reset, memory, rng):
    mem = jnp.where(reset, init_agent_1(), memory)
    obs = jnp.asarray(obs, dtype=jnp.int32)
    r, c = localize(obs)
    facing, held = self_state(obs)

    mem = update_pot_memory(mem, obs, r, c, M1_CNT, M1_COOKED, M1_TIMER, M1_SINCE_EMPTY)
    old_slots = mem[M1_SLOT:M1_SLOT + 4]
    mem = update_slot_memory(mem, obs, r, c, SLOT_CELLS_1, M1_SLOT)
    mem = mem.at[M1_STEP].set(mem[M1_STEP] + 1)

    cnt = mem[M1_CNT:M1_CNT + 3]
    cooked = mem[M1_COOKED]
    timer = mem[M1_TIMER]
    tot = cnt.sum()
    pot_idle = (timer == 0) & (cooked == 0)
    cooking = timer > 0
    is_cooked = cooked == 1
    ntypes = (cnt > 0).sum()
    single_type = jnp.argmax(cnt)
    ptype = jnp.where(tot == 0, -1, jnp.where(ntypes == 1, single_type, -2))
    maj = jnp.where(cnt[1] > cnt[0], 1, 0)
    need_type = _i32(jnp.where(ptype >= 0, ptype, maj))
    can_fill = pot_idle & (tot < 3) & (tot > 0) & (need_type <= 1)

    slots = mem[M1_SLOT:M1_SLOT + 4]
    slot_empty = slots == 0
    slot_plate = slots == 4

    held_raw = (held >= 1) & (held <= 3)
    hk = jnp.clip(held - 1, 0, 2)
    held_none = held == 0
    held_plate = held == 4
    held_dish = held == 5
    held_other = held == 6

    me = obs[2, 2, :]
    dish_counts = me[7:10]
    dish_uniform = ((dish_counts > 0).sum() == 1)

    # --- stale-pot bookkeeping ---
    since_deliver = _i32(jnp.where(mem[M1_LAST_DELIVER] == 1, 0, jnp.minimum(mem[M1_SINCE_DELIVER] + 1, BIG)))
    mem = mem.at[M1_SINCE_DELIVER].set(since_deliver)
    my_units = _i32(jnp.where((mem[M1_LAST_INSERT] == 1) & held_none, mem[M1_MYUNITS] + 1, mem[M1_MYUNITS]))
    pot_empty = tot == 0
    suspect = mem[M1_SUSPECT] == 1
    ev_wrong = mem[M1_EVWRONG] == 1
    dish_bad = mem[M1_DISH_BAD] == 1
    # contents appeared while I still carried a deliverable dish, or on the delivery step itself
    stale_window = (held_dish & ~dish_bad) | (since_deliver == 0)
    suspect = jnp.where(pot_empty, False, suspect | ((tot > 0) & stale_window))
    # partner waiting at the pot (global (2,6), facing right) holding a raw ingredient of another type
    pvis, pv = read_cell(obs, r, c, 2, 6)
    p_at_pot = pvis & (pv[10] == 1) & (pv[13] == 1)
    p_held = classify_item(pv[15:20])
    p_raw_other = (p_held >= 1) & (p_held <= 3) & ((p_held - 1) != ptype)
    # partner already waiting at the pot with the needed ingredient: it will insert next; do not duplicate
    partner_ready = p_at_pot & (p_held == 1 + need_type)
    ev_wrong = jnp.where(pot_empty, False, ev_wrong | (suspect & p_at_pot & p_raw_other & (ptype >= 0)))
    my_units = jnp.where(pot_empty, 0, my_units)
    partner_units = tot - my_units
    confirmed = partner_units >= 2
    pot_bad = suspect & ev_wrong & ~confirmed
    mem = mem.at[M1_SUSPECT].set(_i32(suspect))
    mem = mem.at[M1_EVWRONG].set(_i32(ev_wrong))
    mem = mem.at[M1_MYUNITS].set(_i32(my_units))

    # --- pass-through fallback: pot empty for a long time while a raw ingredient sits on (1,7)/(3,7) ---
    empty_idle = pot_empty & pot_idle
    empty_steps = _i32(jnp.where(empty_idle, jnp.minimum(mem[M1_EMPTY_STEPS] + 1, BIG), 0))
    mem = mem.at[M1_EMPTY_STEPS].set(empty_steps)
    hint_mode = empty_idle & (empty_steps >= HINT_STALL)
    hint_flag = (mem[M1_HINT] == 1) & empty_idle
    # freshness: a counter ingredient is a usable hint only if it appeared after my last delivery
    deliverable_in_hand = held_dish & ~dish_bad
    counter_raw = []
    for k in range(2):
        is_raw_k = (slots[k] >= 1) & (slots[k] <= 2)
        appeared = (old_slots[k] == 0) & is_raw_k
        fresh_old = mem[M1_FRESH + k] == 1
        fresh = jnp.where(appeared, (since_deliver >= 1) & ~deliverable_in_hand,
                          fresh_old & is_raw_k & (since_deliver != 0) & ~deliverable_in_hand)
        mem = mem.at[M1_FRESH + k].set(_i32(fresh))
        counter_raw.append(is_raw_k & fresh)
    hint_goal = _i32(jnp.where(counter_raw[0], 6, 7))
    hint_avail = counter_raw[0] | counter_raw[1]
    # stale raw item blocking a pass-through counter: relocate it to (0,9)/(4,9) so the partner can restock
    stale_raw = [((slots[k] >= 1) & (slots[k] <= 3)) & ~counter_raw[k] for k in range(2)]
    stale_goal = _i32(jnp.where(stale_raw[0], 6, 7))
    garb_goal, garb_found = first_matching([(2, 8), (3, 9)], slot_empty, 2)
    relocate = hint_mode & ~hint_avail & (stale_raw[0] | stale_raw[1]) & garb_found
    garb_flag = (mem[M1_GARB] == 1) & held_raw

    # slots: 0=(1,7) g6, 1=(3,7) g7, 2=(0,9) g8, 3=(4,9) g9
    # raw leftovers go to the pass-through counters first, keeping (0,9)/(4,9) free for parking bad dishes
    order0 = [(0, 6), (2, 8), (3, 9), (1, 7)]
    order1 = [(1, 7), (3, 9), (2, 8), (0, 6)]
    order2 = [(2, 8), (3, 9), (0, 6), (1, 7)]
    orderp = [(2, 8), (3, 9)]

    def pick_order(k, flags):
        g0, f0 = first_matching(order0, flags, 2)
        g1, f1 = first_matching(order1, flags, 2)
        g2, f2 = first_matching(order2, flags, 2)
        g = jnp.where(k == 0, g0, jnp.where(k == 1, g1, g2))
        f = jnp.where(k == 0, f0, jnp.where(k == 1, f1, f2))
        return g, f

    stage_goal, stage_found = pick_order(hk, slot_empty)
    dump_goal, dump_found = first_matching(order2, slot_empty, 5)
    plate_drop_goal, plate_drop_found = first_matching(orderp, slot_empty, 2)
    plate_slot_goal, plate_slot_found = first_matching(orderp, slot_plate, 3)
    dist_tab = jnp.asarray(DIST_1_TAB, dtype=jnp.int32)
    near_plate = jnp.where(dist_tab[4, r, c] < dist_tab[3, r, c], 4, 3)
    plate_goal = jnp.where(plate_slot_found, plate_slot_goal, near_plate)
    # source ingredients from any counter holding the needed type (frees the slot), else the supply
    has_need = slots == (1 + need_type)
    src_goal, src_found = pick_order(need_type, has_need)
    supply_goal = jnp.where(need_type == 1, 1, 0)
    fetch_goal = jnp.where(src_found, src_goal, supply_goal)

    add_ok = pot_idle & (tot < 3) & (tot > 0) & ((ptype == hk) | (ptype == -2))

    rules = [
        (held_dish & dish_uniform & ~dish_bad, 5, True),
        (held_dish & dump_found, dump_goal, True),
        (held_dish, 5, True),
        (held_plate & is_cooked, 2, True),
        (held_plate & cooking, 2, False),
        (held_plate & plate_drop_found, plate_drop_goal, True),
        (held_plate, 2, False),
        (held_raw & add_ok, 2, True),
        (held_raw & hint_flag & (hk <= 1), 2, True),
        (held_raw & garb_flag & garb_found, garb_goal, True),
        (held_raw & stage_found, stage_goal, True),
        (held_raw, 2, False),
        (held_other & dump_found, dump_goal, True),
        (held_other, 2, False),
        (held_none & (is_cooked | cooking), plate_goal, True),
        (held_none & can_fill & ~partner_ready, fetch_goal, True),
        (held_none & hint_mode & hint_avail, hint_goal, True),
        (held_none & relocate, stale_goal, True),
    ]
    goal, inter = select_rules(rules, 2, False)
    next_tab = jnp.asarray(NEXT_1_TAB, dtype=jnp.int32)
    action = nav_action(next_tab, GOALS_1, goal, r, c, facing, inter)

    # --- action bookkeeping for the next step ---
    is_inter = action == A_INTERACT
    delivering = is_inter & held_dish & (goal == 5)
    inserting = is_inter & held_raw & (goal == 2)
    picking = is_inter & held_plate & (goal == 2) & is_cooked
    mem = mem.at[M1_LAST_DELIVER].set(_i32(delivering))
    mem = mem.at[M1_LAST_INSERT].set(_i32(inserting))
    picking_hint = is_inter & held_none & hint_mode & hint_avail & ((goal == 6) | (goal == 7))
    keep_hint = (mem[M1_HINT] == 1) & held_raw & pot_empty
    mem = mem.at[M1_HINT].set(_i32(picking_hint | keep_hint))
    picking_garb = is_inter & held_none & relocate & ~hint_avail & ((goal == 6) | (goal == 7))
    mem = mem.at[M1_GARB].set(_i32(picking_garb | garb_flag))
    new_dish_bad = jnp.where(picking, pot_bad, dish_bad & held_dish)
    mem = mem.at[M1_DISH_BAD].set(_i32(new_dish_bad))

    trace = {
        'r': r, 'c': c, 'held': held, 'goal': goal, 'inter': inter.astype(jnp.int32),
        'pot_tot': tot, 'timer': timer, 'cooked': cooked, 'ptype': ptype,
        'suspect': suspect.astype(jnp.int32), 'ev_wrong': ev_wrong.astype(jnp.int32),
        'dish_bad': dish_bad.astype(jnp.int32), 'my_units': my_units,
    }
    return action, mem, trace
