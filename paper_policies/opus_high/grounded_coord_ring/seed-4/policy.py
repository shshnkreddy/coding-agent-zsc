def _init_memory():
    zero = jnp.zeros((), jnp.int32)
    return {
        "t": zero,
        "recipe": zero - 1,
        "last_press": zero - 100,
        "press_count": zero,
        "dish_step": zero - 100,
        "plate_step": zero - 100,
        "busy_step": zero - 100,
        "change_step": zero - 100,
        "credit": zero + START_CREDIT,
        "seen_step": zero,
        "flip": zero,
        "lit_step": zero - 100,
        "selfserve": zero,
        "pressed_any": zero,
    }


def _goto(nav, pos, slot, want_face, facing, interact):
    """Walk to the slot's cell, turn to `want_face`, then INTERACT or STAY."""
    cells = jnp.asarray(_SLOT_CELL, jnp.int32)
    step = nav[slot, pos]
    arrived = pos == cells[slot]
    settled = jnp.where(facing == want_face,
                        jnp.where(interact, INTERACT, STAY),
                        want_face)
    return jnp.where(arrived, settled, step).astype(jnp.int32)


def _core(obs, reset, memory, rng):
    del rng  # the policy is deterministic
    obs = jnp.asarray(obs).astype(jnp.int32)
    nav = jnp.asarray(_NAV, jnp.int32)
    init = _init_memory()
    mem = {key: jnp.where(reset, init[key], memory[key]).astype(jnp.int32) for key in init}
    t = mem["t"]

    # --- self-localization from the static channels -----------------------
    weights = jnp.arange(1, 10, dtype=jnp.int32)
    view_code = jnp.sum(obs[:, :, 20:29] * weights, axis=2).reshape(25)
    windows = jnp.asarray(_WINDOWS, jnp.int32)
    mismatch = jnp.sum((windows != view_code[None, :]).astype(jnp.int32), axis=1)
    walkable = jnp.asarray(_WALK, jnp.int32) > 0
    pos = jnp.argmin(jnp.where(walkable, mismatch, 9999)).astype(jnp.int32)
    is_inner = jnp.asarray(_INNER, jnp.int32)[pos] > 0

    facing = jnp.argmax(jnp.stack([obs[2, 2, 3], obs[2, 2, 2],
                                   obs[2, 2, 4], obs[2, 2, 1]])).astype(jnp.int32)

    # --- own inventory ----------------------------------------------------
    have_plate = obs[2, 2, 5] > 0
    have_cooked = obs[2, 2, 6] > 0
    ing_counts = obs[2, 2, 7:10]
    have_ing = jnp.sum(ing_counts) > 0
    ing_type = jnp.argmax(ing_counts).astype(jnp.int32)
    held_dish = have_plate & have_cooked
    held_plate_only = have_plate & jnp.logical_not(have_cooked)
    held_none = jnp.logical_not(have_plate) & jnp.logical_not(have_ing)

    # --- recipe displays in view (always-on indicator or active button) ---
    shown = jnp.sum(obs[:, :, 36:39], axis=(0, 1))
    shown_any = jnp.sum(shown) > 0
    shown_type = jnp.argmax(shown).astype(jnp.int32)
    prev_recipe = mem["recipe"]
    recipe = jnp.where(shown_any, shown_type, prev_recipe).astype(jnp.int32)
    changed = shown_any & (prev_recipe >= 0) & (shown_type != prev_recipe)
    change_step = jnp.where(changed, t, mem["change_step"]).astype(jnp.int32)

    # --- pot state (the inner seat always has the pot in view) ------------
    pot_mask = obs[:, :, 22].reshape(25)
    pot_vis = jnp.max(pot_mask) > 0
    pot_cell = jnp.argmax(pot_mask)
    pot_item = obs[:, :, 29:34].reshape(25, 5)[pot_cell]
    pot_cooked = (pot_item[1] > 0) & pot_vis
    pot_counts = pot_item[2:5]
    pot_n = jnp.where(pot_vis, jnp.sum(pot_counts), 0)
    pot_type = jnp.argmax(pot_counts).astype(jnp.int32)
    pot_timer = jnp.where(pot_vis, obs[:, :, 39].reshape(25)[pot_cell], 0)

    # --- partner ----------------------------------------------------------
    partner_mask = obs[:, :, 10].reshape(25)
    partner_vis = jnp.max(partner_mask) > 0
    partner_cell = jnp.argmax(partner_mask)
    partner_item = obs[:, :, 15:20].reshape(25, 5)[partner_cell]
    partner_dish = partner_vis & (partner_item[0] > 0) & (partner_item[1] > 0)
    # An empty plate in hand means the pot is already loaded and a delivery --
    # and with it a freshly sampled recipe -- is roughly a cook-timer away.
    partner_plate = partner_vis & (partner_item[0] > 0) & (partner_item[1] == 0)
    # An ingredient in hand means the dish is already committed: the partner
    # does not need the recipe displayed right now.
    partner_ing = partner_vis & (jnp.sum(partner_item[2:5]) > 0)

    # ======================================================================
    # Inner cook
    # ======================================================================
    # Follow the pot's own contents whenever it holds something, so a stale or
    # mistaken recipe can never strand the pot half full of the wrong thing.
    target = jnp.where(pot_n > 0, pot_type, recipe).astype(jnp.int32)
    known = (target == 0) | (target == 1)
    top = target == 0

    sup_slot = jnp.where(top, S_SUP_TOP, S_SUP_BOT)
    pot_slot = jnp.where(top, S_POT_TOP, S_POT_BOT)
    pot_face = jnp.where(top, DOWN, UP)
    plate_slot = jnp.where(top, S_PLATE_TOP, S_PLATE_BOT)
    # Use the nearer button; if an activation is somehow ineffective (an item
    # on the button cell blocks it), alternate to the other one.
    near_top = (pos // 9) <= 4
    use_top_button = near_top != (((mem["press_count"] // 2) % 2) == 1)
    btn_slot = jnp.where(use_top_button, S_POT_TOP, S_POT_BOT)
    btn_face = jnp.where(use_top_button, UP, DOWN)
    # Rotating dump target: a fallback for an item that does not fit the plan.
    dump_pick = (t // 13) % 4
    dump_slot = jnp.asarray([S_SUP_TOP, S_PLATE_TOP, S_SUP_BOT, S_PLATE_BOT], jnp.int32)[dump_pick]
    dump_face = jnp.asarray([UP, UP, DOWN, DOWN], jnp.int32)[dump_pick]

    a_deliver = _goto(nav, pos, S_DELIVER, LEFT, facing, True)
    a_deposit = _goto(nav, pos, pot_slot, pot_face, facing, True)
    # Plate up from (4,3): that cell touches both the pot and the delivery
    # station, so a finished dish is two steps from being handed in.
    a_plate_up = _goto(nav, pos, S_DELIVER, RIGHT, facing, True)
    a_wait = _goto(nav, pos, S_DELIVER, RIGHT, facing, False)
    a_plate = _goto(nav, pos, plate_slot, RIGHT, facing, True)
    a_grab = _goto(nav, pos, sup_slot, LEFT, facing, True)
    a_press_in = _goto(nav, pos, btn_slot, btn_face, facing, True)
    a_dump = _goto(nav, pos, dump_slot, dump_face, facing, True)

    busy = pot_cooked | (pot_timer > 0)
    idle = jnp.logical_not(busy) & (pot_n < 3)
    not_known = jnp.logical_not(known)

    inner_act = jnp.asarray(STAY, jnp.int32)
    # pot idle: learn the recipe, then load three matching ingredients
    inner_act = jnp.where(idle & not_known & held_none, a_press_in, inner_act)
    inner_act = jnp.where(idle & not_known & jnp.logical_not(held_none), a_dump, inner_act)
    inner_act = jnp.where(idle & known & held_none, a_grab, inner_act)
    inner_act = jnp.where(idle & known & have_ing & (ing_type == target), a_deposit, inner_act)
    inner_act = jnp.where(idle & known & have_ing & (ing_type != target), a_dump, inner_act)
    inner_act = jnp.where(idle & known & held_plate_only, a_dump, inner_act)
    # pot cooking or ready: fetch a plate, wait by the pot, then plate up
    inner_act = jnp.where(busy & held_none, a_plate, inner_act)
    inner_act = jnp.where(busy & have_ing, a_dump, inner_act)
    inner_act = jnp.where((pot_timer > 0) & held_plate_only, a_wait, inner_act)
    inner_act = jnp.where(pot_cooked & held_plate_only, a_plate_up, inner_act)
    # carrying a finished dish: deliver it
    inner_act = jnp.where(held_dish, a_deliver, inner_act)

    delivering = held_dish & (pos == _SLOT_CELL[S_DELIVER]) & (facing == LEFT) & (inner_act == INTERACT)
    inner_pressing = (idle & not_known & held_none
                      & (inner_act == INTERACT) & (facing == btn_face))
    # A correct delivery samples a fresh recipe, so forget the old one.
    inner_recipe = jnp.where(delivering, -1, recipe).astype(jnp.int32)
    inner_press_count = jnp.where(inner_pressing, mem["press_count"] + 1,
                                  jnp.where(known, 0, mem["press_count"])).astype(jnp.int32)
    inner_last_press = jnp.where(inner_pressing, t, mem["last_press"]).astype(jnp.int32)

    # ======================================================================
    # Outer informant
    # ======================================================================
    # Post by the button on the side holding the current recipe's pile: that is
    # where a partner cooking this recipe has to work, so the partner stays
    # visible and the activation lands close to when it is needed.
    # If the partner never shows up on this side, the guess about where it
    # works is wrong, so try the other half of the ring instead.
    unseen = (t - mem["seen_step"]) >= POST_PATIENCE
    flip = jnp.where(unseen, 1 - mem["flip"], mem["flip"]).astype(jnp.int32)
    seen_step = jnp.where(partner_vis | unseen, t, mem["seen_step"]).astype(jnp.int32)
    want_bot = (recipe == 1) != (flip > 0)
    post_slot = jnp.where(want_bot, S_POST_BOT, S_POST_TOP)
    post_face = jnp.where(want_bot, UP, DOWN)

    button_lit = jnp.max(obs[:, :, 24] * jnp.sum(obs[:, :, 36:39], axis=2)) > 0
    dish_step = jnp.where(partner_dish, t, mem["dish_step"]).astype(jnp.int32)
    plate_step = jnp.where(partner_plate, t, mem["plate_step"]).astype(jnp.int32)
    busy_step = jnp.where(partner_ing, t, mem["busy_step"]).astype(jnp.int32)
    # Proof that the information being bought turns into cooking: a resampled
    # recipe (only a correct delivery resamples), a cooked dish in the
    # partner's hands, or an ingredient run followed by fetching a plate.
    dish_edge = partner_dish & (mem["dish_step"] < t - 1)
    plate_edge = (partner_plate & (mem["plate_step"] < t - 1)
                  & ((t - mem["busy_step"]) <= COOK_WINDOW))
    proof = (PROOF_CREDIT * (changed | dish_edge).astype(jnp.int32)
             + plate_edge.astype(jnp.int32))

    since_press = t - mem["last_press"]
    trig_first = mem["pressed_any"] == 0
    trig_dish = (t - dish_step) <= 4
    trig_change = (t - change_step) <= 6
    trig_blind = since_press >= PRESS_TIMEOUT
    # A plated partner is one cook timer away from needing the next recipe;
    # activating a little before that puts the display up when they look.
    since_plate = t - plate_step
    trig_plate = (since_plate >= PLATE_LEAD) & (since_plate <= PLATE_LEAD + 4)
    trig_evidenced = trig_first | trig_dish | trig_plate | trig_change
    # Do not spend on information the partner visibly does not need yet.
    suppress = (t - busy_step) <= 2

    # A display we cannot account for (our own activation shows for exactly the
    # next 9 observations) was bought by the partner: it serves itself, so our
    # spending would be redundant.  Stand down, but resume if it ever stops.
    partner_lit = button_lit & (since_press > 9)
    lit_edge = partner_lit & (mem["lit_step"] < t - 1)
    lit_step = jnp.where(partner_lit, t, mem["lit_step"]).astype(jnp.int32)
    selfserve = jnp.where((t - lit_step) > SELFSERVE_FORGET, 0,
                          mem["selfserve"] + lit_edge.astype(jnp.int32)).astype(jnp.int32)

    # Spending budget: a partner that never turns activations into deliveries
    # stops earning them, so an inert or erratic partner costs only a little.
    credit = jnp.minimum(mem["credit"] + proof, MAX_CREDIT)
    press_ok = (pos == jnp.asarray(_SLOT_CELL, jnp.int32)[post_slot])
    press_ok = (press_ok & (facing == post_face) & jnp.logical_not(button_lit)
                & jnp.logical_not(suppress) & (credit > 0)
                & (selfserve < SELFSERVE_LIMIT)
                & (since_press >= PRESS_MIN_GAP) & (trig_evidenced | trig_blind))
    outer_act = jnp.where(press_ok, jnp.asarray(INTERACT, jnp.int32),
                          _goto(nav, pos, post_slot, post_face, facing, False)).astype(jnp.int32)

    outer_credit = (credit - press_ok.astype(jnp.int32)).astype(jnp.int32)
    outer_last_press = jnp.where(press_ok, t, mem["last_press"]).astype(jnp.int32)
    outer_pressed_any = jnp.maximum(mem["pressed_any"], press_ok.astype(jnp.int32))

    # ======================================================================
    action = jnp.where(is_inner, inner_act, outer_act).astype(jnp.int32)
    next_mem = {
        "t": (t + 1).astype(jnp.int32),
        "recipe": jnp.where(is_inner, inner_recipe, recipe).astype(jnp.int32),
        "last_press": jnp.where(is_inner, inner_last_press, outer_last_press).astype(jnp.int32),
        "press_count": jnp.where(is_inner, inner_press_count, mem["press_count"]).astype(jnp.int32),
        "dish_step": dish_step,
        "plate_step": plate_step,
        "busy_step": busy_step,
        "change_step": change_step,
        "credit": jnp.where(is_inner, mem["credit"], outer_credit).astype(jnp.int32),
        "seen_step": jnp.where(is_inner, mem["seen_step"], seen_step).astype(jnp.int32),
        "flip": jnp.where(is_inner, mem["flip"], flip).astype(jnp.int32),
        "lit_step": jnp.where(is_inner, mem["lit_step"], lit_step).astype(jnp.int32),
        "selfserve": jnp.where(is_inner, mem["selfserve"], selfserve).astype(jnp.int32),
        "pressed_any": jnp.where(is_inner, mem["pressed_any"], outer_pressed_any).astype(jnp.int32),
    }
    trace = {
        "pos": pos,
        "is_inner": is_inner.astype(jnp.int32),
        "recipe": recipe,
        "pot_n": pot_n.astype(jnp.int32),
        "pot_timer": pot_timer.astype(jnp.int32),
        "credit": credit.astype(jnp.int32),
        "selfserve": selfserve.astype(jnp.int32),
        "action": action,
    }
    return action, next_mem, trace


