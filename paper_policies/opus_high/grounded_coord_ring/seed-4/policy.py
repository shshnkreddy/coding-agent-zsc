"""Grounded role-split policy for overcooked_v2 `grounded_coord_ring`.

The two spawn regions are disconnected.  Seat 1 lives in the 8-cell inner room
around the pot and can reach the ingredient 0/1 piles, both plate piles, both
delivery stations and both recipe buttons; seat 0 lives in the outer ring and
can reach the always-on recipe indicators and both recipe buttons, but never
the pot.  So the inner seat cooks alone and only ever lacks one thing -- the
target recipe -- while the outer seat is the only one that can read the
always-on indicator.

Both roles avoid private signalling conventions:

* the inner cook reads the recipe from any visible indicator or active button
  and, when none is visible, buys the information itself by activating a
  button (cost 5, still worth +20 on delivery);
* the outer informant activates a button -- the environment's own self
  describing information channel -- when grounded evidence says a partner is
  about to need a fresh recipe, with bounded spending if nothing ever happens.

Neither role assumes the partner runs this policy.  The role is chosen by self
localization, so the two act functions are interchangeable.
"""

