_PERMS = ((0, 1, 2), (0, 2, 1), (1, 0, 2), (1, 2, 0), (2, 0, 1), (2, 1, 0))
_DIRS = ((1, 0), (-1, 0), (0, 1), (0, -1))

_TOPK = 16
_NEG = -1.0e9

# Tunables.
_END_CONT = (9.0, 9.0, 9.0, 9.0, 5.5, 3.4, 2.8, 0.7)   # per-turn continuation value
_MIN_END_PROB = 0.10   # never end on a near-hopeless board
_EDGE_BONUS = 0.15     # partial credit for a single same-colour adjacency
_SURR_WEIGHT = 0.08    # tie-break weight of the shape surrogate
_OBS_KN = -0.30        # among unseen cards, prefer ones isolated from known cards
_BETA_PARTNER = 0.0    # competence prior on partner relocations; 0 = off, and
                       # off is deliberate: it assumes nothing about partners


def _triple_edges(pos, tri):
    """Same-triple orthogonal adjacency counts. pos: [..., 9, 2]."""
    delta = jnp.abs(pos[..., :, None, :] - pos[..., None, :, :]).sum(-1)
    adj = (delta == 1).astype(jnp.float32)
    edges = (adj[..., tri[:, 0], tri[:, 1]]
             + adj[..., tri[:, 0], tri[:, 2]]
             + adj[..., tri[:, 1], tri[:, 2]])
    return edges, adj


def _success_prob(conn, parts, weights, total):
    """Posterior probability that all three colours are connected."""
    joint = (conn[..., parts[:, 0]] * conn[..., parts[:, 1]]
             * conn[..., parts[:, 2]])
    return (joint * weights).sum(-1) / total


def init_agent():
    return {
        'known': -jnp.ones(9, dtype=jnp.int32),
        'step': jnp.asarray(0, dtype=jnp.int32),
        'prev_pos': jnp.zeros((9, 2), dtype=jnp.int32),
        'was_active': jnp.asarray(0, dtype=jnp.int32),
        'log_w': jnp.zeros(280, dtype=jnp.float32),
    }


def agent_act(obs, reset, memory, rng):
    tri = jnp.asarray(_TRIPLES, dtype=jnp.int32)          # [84, 3]
    parts = jnp.asarray(_PARTITIONS, dtype=jnp.int32)     # [280, 3]
    dirs = jnp.asarray(_DIRS, dtype=jnp.int32)
    cards = jnp.arange(9, dtype=jnp.int32)
    colors = jnp.arange(3, dtype=jnp.int32)
    cand_card = jnp.repeat(cards, 36)                     # [324]

    nf = obs.node_features.astype(jnp.int32)
    pos = obs.positions.astype(jnp.int32)
    legal = obs.legal_actions

    # ---------------- private colour memory ----------------
    known_prev = jnp.where(reset, -jnp.ones(9, dtype=jnp.int32), memory['known'])
    step = jnp.where(reset, jnp.asarray(0, jnp.int32), memory['step'])
    colour_rows = nf[0:9, 0:3]
    seen_now = colour_rows.sum(1) > 0
    known = jnp.where(seen_now, jnp.argmax(colour_rows, axis=1).astype(jnp.int32),
                      known_prev)
    active = nf[0, 10] == 1
    substep = nf[0, 11]
    unknown = known < 0
    known_card = ~unknown

    # ---------------- exact posterior over colour assignments ----------------
    compat = (known[:, None] < 0) | (known[:, None] == colors[None, :])
    tri_ok = (compat[tri[:, 0]] & compat[tri[:, 1]]
              & compat[tri[:, 2]]).astype(jnp.float32)          # [84, 3]
    part_ok = tri_ok[parts]                                     # [280, 3, 3]
    weights = jnp.zeros(parts.shape[0], dtype=jnp.float32)
    for perm in _PERMS:
        weights = weights + (part_ok[:, 0, perm[0]] * part_ok[:, 1, perm[1]]
                             * part_ok[:, 2, perm[2]])

    # ---------------- competence prior on partner relocations ----------------
    # Which part of each partition holds each card.  Whether two cards share a
    # colour depends on the partition alone, never on which colour a part gets.
    member = jnp.zeros((parts.shape[0], 9), dtype=jnp.int32)
    for j in range(3):
        in_part = (tri[parts[:, j]][:, :, None]
                   == cards[None, None, :]).any(1)              # [280, 9]
        member = member + j * in_part.astype(jnp.int32)
    same_part = (member[:, :, None] == member[:, None, :]).astype(jnp.float32)

    prev_pos = jnp.where(reset, pos, memory['prev_pos'])
    was_active = jnp.where(reset, jnp.asarray(1, jnp.int32), memory['was_active'])
    log_w = jnp.where(reset, jnp.zeros(parts.shape[0], dtype=jnp.float32),
                      memory['log_w'])
    changed = (pos != prev_pos).any(-1)
    mover = jnp.argmax(changed)
    partner_moved = (changed.sum() == 1) & (was_active == 0)
    gap = jnp.abs(pos - pos[mover]).sum(-1)
    neighbours = ((gap == 1) & (cards != mover)).astype(jnp.float32)
    support = (same_part[:, mover, :] * neighbours[None, :]).sum(-1)   # [280]
    log_w = log_w + jnp.where(partner_moved, _BETA_PARTNER * support, 0.0)
    log_w = log_w - log_w.max()
    weights = weights * jnp.exp(log_w)
    total = jnp.maximum(weights.sum(), 1e-6)

    next_memory = {'known': known, 'step': step + 1, 'prev_pos': pos,
                   'was_active': active.astype(jnp.int32), 'log_w': log_w}

    # Marginal probability that a given triple is exactly one colour class.
    tri_marg = jnp.zeros(tri.shape[0], dtype=jnp.float32)
    for j in range(3):
        tri_marg = tri_marg.at[parts[:, j]].add(weights)
    tri_marg = tri_marg / total
    marg_total = jnp.maximum(tri_marg.sum(), 1e-6)

    # Per-card colour marginals (uniform over the undealt remainder).
    onehot_known = (known[:, None] == colors[None, :]).astype(jnp.float32)
    remaining = jnp.maximum(3.0 - onehot_known.sum(0), 0.0)
    n_unknown = jnp.maximum(unknown.sum().astype(jnp.float32), 1.0)
    card_marg = jnp.where(unknown[:, None], remaining[None, :] / n_unknown,
                          onehot_known)

    # ---------------- current board ----------------
    edges_now, adj_now = _triple_edges(pos, tri)
    conn_now = (edges_now >= 2.0).astype(jnp.float32)
    prob_now = _success_prob(conn_now, parts, weights, total)

    # ---------------- hint bookkeeping ----------------
    hint_set = nf[9:13, 3:6]                       # [4, 3] multi-hot
    hint_pos = nf[9:13, 6:8]
    revealed = hint_set.sum(1) > 0
    placed = nf[9:13, 8] == 1
    n_unrevealed = (~revealed).sum().astype(jnp.float32)
    n_ready = (revealed & ~placed).sum().astype(jnp.float32)

    at_pos = (pos[None, :, :] == hint_pos[:, None, :]).all(-1).astype(jnp.float32)
    match_prob = (card_marg[None, :, :]
                  * hint_set[:, None, :].astype(jnp.float32)).sum(-1)
    q_placed = (at_pos * match_prob).sum(-1)
    value_placed = (placed.astype(jnp.float32) * (2.0 * q_placed - 1.0)).sum()
    value_now = 5.0 * n_unrevealed + 2.0 * n_ready + value_placed

    # ---------------- substeps 0/1: observe an unseen card ----------------
    known_neighbours = (adj_now * known_card[None, :].astype(jnp.float32)).sum(-1)
    obs_score = jnp.where(legal[1:10],
                          1.0 + 2.0 * unknown.astype(jnp.float32)
                          + _OBS_KN * known_neighbours
                          - 0.01 * cards.astype(jnp.float32), _NEG)
    observe_action = (1 + jnp.argmax(obs_score)).astype(jnp.int32)

    # ---------------- substep 2: choose a move ----------------
    neigh = (pos[:, None, :] + dirs[None, :, :]).reshape(36, 2)
    cand_cell = jnp.tile(neigh, (9, 1))                          # [324, 2]
    in_range = ((cand_cell >= 0) & (cand_cell <= 8)).all(-1)
    clipped = jnp.clip(cand_cell, 0, 8)
    move_id = (10 + cand_card * 81 + clipped[:, 0] * 9
               + clipped[:, 1]).astype(jnp.int32)
    move_ok = in_range & legal[move_id]
    is_moved = cards[None, :] == cand_card[:, None]
    cand_pos = jnp.where(is_moved[:, :, None], cand_cell[:, None, :],
                         pos[None, :, :])
    cand_edges, _ = _triple_edges(cand_pos, tri)                 # [324, 84]
    cand_conn = (cand_edges >= 2.0).astype(jnp.float32)
    surrogate = (((cand_conn + _EDGE_BONUS * cand_edges)
                  * tri_marg[None, :]).sum(-1)) / marg_total
    ranked = jnp.where(move_ok, surrogate, _NEG)
    top_vals, top_idx = jax.lax.top_k(ranked, _TOPK)
    top_prob = _success_prob(cand_conn[top_idx], parts, weights, total)
    final_score = jnp.where(top_vals > -1.0e8,
                            top_prob + _SURR_WEIGHT * top_vals, _NEG)
    pick = jnp.argmax(final_score)
    best_move = move_id[top_idx[pick]]
    best_move_prob = top_prob[pick]

    # ---------------- substep 3: reveal or place a hint ----------------
    place_id = (743 + jnp.arange(4, dtype=jnp.int32)[:, None] * 81
                + pos[None, :, 0] * 9 + pos[None, :, 1]).astype(jnp.int32)
    place_legal = legal[place_id]                                # [4, 9]
    hit = hint_set[:, jnp.clip(known, 0, 2)] == 1                # [4, 9]
    correct = hit & known_card[None, :]
    same_colour = ((known[:, None] == known[None, :])
                   & known_card[None, :] & known_card[:, None])
    anchor = (adj_now * same_colour.astype(jnp.float32)).sum(-1)
    hint_size = hint_set.sum(1).astype(jnp.float32)
    place_value = (100.0 * correct.astype(jnp.float32)
                   + 20.0 * known_card[None, :].astype(jnp.float32)
                   + 3.0 * anchor[None, :]
                   - 1.0 * hint_size[:, None]
                   - 0.01 * cards[None, :].astype(jnp.float32))
    place_value = jnp.where(place_legal, place_value, _NEG)
    flat_best = jnp.argmax(place_value.reshape(-1))
    place_action = place_id.reshape(-1)[flat_best]
    have_correct = place_value.reshape(-1)[flat_best] >= 100.0
    reveal_action = (739 + jnp.argmax(~revealed)).astype(jnp.int32)
    can_reveal = (~revealed).any() & legal[reveal_action]
    hint_action = jnp.where(can_reveal & jnp.logical_not(have_correct),
                            reveal_action, place_action)

    # ---------------- substep 0: stop or play on ----------------
    # Ending banks `value_now` with probability `prob_now`; playing on is worth
    # the tabulated continuation value for this turn, which falls as the
    # remaining stake shrinks (one hint is spent every turn).
    turn = jnp.clip(step // 4, 0, 7)
    cont = jnp.asarray(_END_CONT, dtype=jnp.float32)[turn]
    do_end = ((prob_now * value_now > cont) & (prob_now >= _MIN_END_PROB)
              & legal[1067])
    open_action = jnp.where(do_end, jnp.asarray(1067, jnp.int32), observe_action)

    action = jnp.where(substep == 0, open_action,
                       jnp.where(substep == 1, observe_action,
                                 jnp.where(substep == 2, best_move,
                                           hint_action)))
    action = jnp.where(active, action, jnp.asarray(0, jnp.int32))
    action = jnp.where(legal[action], action,
                       jnp.argmax(legal).astype(jnp.int32)).astype(jnp.int32)

    trace = {
        'prob_now': prob_now.astype(jnp.float32),
        'prob_after_move': best_move_prob.astype(jnp.float32),
        'value_now': value_now.astype(jnp.float32),
        'threshold': cont.astype(jnp.float32),
        'num_known': known_card.sum().astype(jnp.float32),
        'ended': (action == 1067).astype(jnp.float32),
        'board': jnp.concatenate([pos.reshape(-1), known]).astype(jnp.float32),
    }
    return action, next_memory, trace
