"""Cooperative 9-card Yokai policy.

Each seat acts only on its own observations. It keeps the colours it has
privately seen in memory, maintains the exact posterior over the colour
assignments consistent with those observations, moves cards so that the
posterior probability of "every colour orthogonally connected" is maximal,
places hints only where it knows the placement is correct, and ends the game
when the expected terminal value of stopping beats an estimate of continuing.

No partner convention is assumed: nothing is inferred from the partner beyond
the public board state, and nothing is signalled to the partner.
"""

